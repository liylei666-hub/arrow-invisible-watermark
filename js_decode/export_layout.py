#!/usr/bin/env python3
"""Regenerate ``js_decode/layout.js`` from the Python edge design.

The mini program does not rasterize the master PNG. Cell geometry is exactly
``arrow_wm.build_layout`` on ``ArrowDesign.mask1``, and the registration
template is the unwatermarked plate at 1/4 resolution (OpenCV INTER_AREA),
run-length encoded. Re-run this after a layout or master-art change:

    python js_decode/export_layout.py
"""
from __future__ import annotations

import json
import os
import sys

import cv2
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

import arrow_wm as A  # noqa: E402


def _rle(flat: np.ndarray) -> bytes:
    raw = bytearray()
    prev = int(flat[0])
    n = 1
    for value in flat[1:]:
        value = int(value)
        if value == prev and n < 255:
            n += 1
            continue
        raw.append(n)
        raw.append(prev)
        prev = value
        n = 1
    raw.append(n)
    raw.append(prev)
    return bytes(raw)


def _expand_rle(raw: bytes) -> np.ndarray:
    out = []
    for i in range(0, len(raw), 2):
        out.extend([raw[i + 1]] * raw[i])
    return np.asarray(out, np.uint8)


def _logo_scale(design: A.ArrowDesign) -> float:
    """Identity-homography logo scale: ref-quad width / canvas width.

    Matches ``WatermarkDecoder._logo_scale`` when the image→plate homography
    is the identity. ECC on a clean plate nudges this by a few ten-thousandths.
    """
    q = design.ref_quad.astype(np.float64)
    w = 0.5 * (np.linalg.norm(q[0] - q[1]) + np.linalg.norm(q[2] - q[3]))
    return float(w / A.CANVAS_W)


def build_layout_object() -> dict:
    design = A.ArrowDesign(verbose=False)
    if len(design.cells) != A.N_CELLS:
        raise SystemExit(f"expected {A.N_CELLS} cells, got {len(design.cells)}")

    qw = A.CANVAS_W // 4
    qh = A.CANVAS_H // 4
    quarter = cv2.resize(design.template, (qw, qh), interpolation=cv2.INTER_AREA)
    # JS repeats this with a 4×4 box mean and round-half-to-even. Those agree
    # with INTER_AREA on this master (uint8 sources, exact factor of 4).
    box = design.template.astype(np.float64).reshape(qh, 4, qw, 4).mean(axis=(1, 3))
    if int(np.max(np.abs(np.rint(box).astype(np.int16) - quarter.astype(np.int16)))) != 0:
        raise SystemExit("quarter template no longer matches 4x4 box-mean rounding")

    cells = []
    for c in design.cells:
        cells.append({
            "idx": int(c.idx),
            "track": int(c.track),
            "y0": int(c.y0),
            "y1": int(c.y1),
            "x_mid": float(c.x_mid),
            "y_mid": float(c.y_mid),
            "slope": float(c.slope),
            "width": float(c.width),
            "half_win": int(c.half_win),
        })
    rle = _rle(quarter.ravel())
    if not np.array_equal(_expand_rle(rle), quarter.ravel()):
        raise SystemExit("template RLE did not round-trip")
    return {
        "canvasW": A.CANVAS_W,
        "canvasH": A.CANVAS_H,
        "quarterW": qw,
        "quarterH": qh,
        "nCells": A.N_CELLS,
        "nBits": A.N_BITS,
        "logoScale": _logo_scale(design),
        "cells": cells,
        "templateRleHex": rle.hex(),
    }


def main() -> int:
    payload = build_layout_object()
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "layout.js")
    body = json.dumps(payload, ensure_ascii=True, separators=(",", ":"))
    text = (
        "/* Generated by js_decode/export_layout.py — do not edit by hand.\n"
        "   Cell geometry is arrow_wm.build_layout on the ARROW master.\n"
        "   templateRleHex is the unwatermarked plate at 1/4 resolution. */\n"
        '"use strict";\n'
        "module.exports = "
        + body
        + ";\n"
    )
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out_path} ({os.path.getsize(out_path)} bytes, "
          f"{payload['nCells']} cells, logoScale={payload['logoScale']:.6f})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
